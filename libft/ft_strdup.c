#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*dup;
	int		slen;
	int		i;

	slen = ft_strlen(s);
	dup = (char *)ft_calloc(slen + 1, sizeof(char));
	if (!dup)
		return (NULL);
	i = 0;
	while (s[i])
	{
		dup[i] = s[i];
		i++;
	}
	dup[i] = '\0';
	return (dup);
}
