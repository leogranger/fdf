#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	char		c;
	long int	nbr;

	nbr = n;
	if (nbr < 0)
	{
		write(fd, "-", 1);
		nbr *= -1;
	}
	if (nbr > 9)
		ft_putnbr_fd(nbr / 10, fd);
	c = (nbr % 10) + 48;
	write(fd, &c, 1);
}
